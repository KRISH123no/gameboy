"""A 5x7 bitmap font, drawn by hand.

Rendering a normal font at eight pixels and scaling it up does not produce
pixel art — it produces a blurred small font. Strokes land between pixels,
antialiasing turns them grey, and the result reads as broken rather than
retro.

So the glyphs are written out as bits. Every stroke is one pixel wide and
lands exactly where it was put, at any scale, forever. Uppercase only,
because the Game Boy's own fonts were, and because a lowercase 'g' needs a
descender this grid has no room for.
"""

